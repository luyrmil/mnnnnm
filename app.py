for i in range(5):
    for n, (ho, names) in enumerate(datalist[i]):
        arr[i][n]["호"] = ho
        arr[i][n]["이름"].extend(names)


def find_p(name):
    results = []
    for i in range(5):
        for j in range(37):
            if name in arr[i][j]["이름"]:
                ho = arr[i][j]["호"]
                floor = i + 1
                results.append({"name": name, "ho": ho, "floor": floor})
    return results


@app.route("/")
def index():
    return render_template("index.html")


@app.route("/search")
def search():
    name = request.args.get("name", "").strip()
    if not name:
        return jsonify({"results": [], "error": "이름을 입력해주세요."})
    results = find_p(name)
    if not results:
        return jsonify({"results": [], "error": f"'{name}' 을(를) 찾을 수 없습니다."})
    return jsonify({"results": results, "error": None})


